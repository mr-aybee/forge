/** Language by file name, then extension, then shebang. */
export function detectLanguage(name: string, firstLine: string): Language {
  const n = name.toLowerCase();
  if (BY_NAME[n]) return BY_NAME[n];
  if (n.startsWith("dockerfile.") || n.endsWith(".dockerfile")) return "dockerfile";
  if (n.startsWith(".env.")) return "env";
  if (n.endsWith(".conf") && /^\s*(server|http|events|upstream|location)\b|\{\s*$/.test(firstLine)) return "nginx";
  const ext = n.includes(".") ? n.slice(n.lastIndexOf(".") + 1) : "";
  if (BY_EXT[ext]) return BY_EXT[ext];
  if (firstLine.startsWith("#!")) {
    if (/python/.test(firstLine)) return "python";
    if (/node|deno|bun/.test(firstLine)) return "javascript";
    if (/ruby/.test(firstLine)) return "ruby";
    if (/perl/.test(firstLine)) return "perl";
    if (/php/.test(firstLine)) return "php";
    if (/pwsh|powershell/.test(firstLine)) return "powershell";
    if (/(ba|z|da|k)?sh\b/.test(firstLine)) return "shell";
  }
  if (firstLine.startsWith("<?xml")) return "xml";
  if (firstLine.startsWith("<?php")) return "php";
  return "plain";
}
